#!/usr/bin/env python3
"""Writes the grapheme cluster tables dropLastCharacter uses (UAX #29) for the C++ and Kotlin ports.

    python3 Android/tools/grapheme/generate.py <ucd dir>

<ucd dir> holds Unicode's GraphemeBreakProperty.txt, emoji-data.txt and DerivedCoreProperties.txt
of one version (https://www.unicode.org/Public/<version>/ucd/: auxiliary/, emoji/ and the top).
Writes Windows/engine/src/GraphemeTables.h and
Android/engine/src/main/kotlin/com/netmaru/rea/engine/GraphemeTables.kt.
"""
import os
import re
import sys

# Class numbers shared by both ports. LV/LVT (the precomposed syllables) are computed, not listed.
CLASSES = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark",
           "L", "V", "T", "LV", "LVT", "Extended_Pictographic"]
INCB = ["None", "Consonant", "Extend", "Linker"]
LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)(?:\s*;\s*([A-Za-z_]+))?")


def ranges(path, keep):
    """(start, end, value) for each line `keep(property, value)` names a value for."""
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = LINE.match(line)
            if not m:
                continue
            value = keep(m.group(3), m.group(4))
            if value is not None:
                out.append((int(m.group(1), 16), int(m.group(2) or m.group(1), 16), value))
    return out


def merged(items):
    out = []
    for start, end, value in sorted(items):
        if out and out[-1][2] == value and out[-1][1] + 1 == start:
            out[-1] = (out[-1][0], end, value)
        else:
            assert not out or out[-1][1] < start, "overlapping ranges"
            out.append((start, end, value))
    return out


def version(path):
    with open(path, encoding="utf-8") as f:
        return re.search(r"-(\d+\.\d+\.\d+)\.txt", f.readline()).group(1)


def main(ucd):
    gbp = os.path.join(ucd, "GraphemeBreakProperty.txt")
    v = version(gbp)
    breaks = ranges(gbp, lambda p, _: CLASSES.index(p) if p not in ("LV", "LVT") else None)
    breaks += ranges(os.path.join(ucd, "emoji-data.txt"),
                     lambda p, _: CLASSES.index(p) if p == "Extended_Pictographic" else None)
    breaks = merged(breaks)
    incb = merged(ranges(os.path.join(ucd, "DerivedCoreProperties.txt"),
                         lambda p, value: INCB.index(value) if p == "InCB" else None))
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
    head = f"Generated by Android/tools/grapheme/generate.py from Unicode {v}; do not edit."

    def cpp(name, table):
        rows = ",\n".join(f"    {{0x{s:X}, 0x{e:X}, {c}}}" for s, e, c in table)
        return f"inline constexpr GraphemeRange {name}[] = {{\n{rows},\n}};\n"

    with open(os.path.join(root, "Windows/engine/src/GraphemeTables.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"// {head}\n#pragma once\n\nnamespace rea {{\n\n"
                f"/** A run of code points with one value: a Grapheme_Cluster_Break class (or {len(CLASSES) - 1},\n"
                f" *  Extended_Pictographic), or an Indic_Conjunct_Break value. */\n"
                "struct GraphemeRange { char32_t start, end; unsigned char value; };\n\n"
                f"/** {', '.join(f'{i} {c}' for i, c in enumerate(CLASSES))}. */\n" + cpp("graphemeBreaks", breaks) +
                f"\n/** {', '.join(f'{i} {c}' for i, c in enumerate(INCB))}. */\n" + cpp("indicConjunctBreaks", incb) +
                "\n} // namespace rea\n")

    def kt(table):
        text = " ".join(f"{s:X}-{e:X}:{c}" for s, e, c in table)
        return "\n".join(f'        "{text[i:i + 100]}" +' for i in range(0, len(text), 100)) + '\n        ""'

    with open(os.path.join(root, "Android/engine/src/main/kotlin/com/netmaru/rea/engine/GraphemeTables.kt"), "w",
              encoding="utf-8", newline="\n") as f:
        f.write(f"// {head}\npackage com.netmaru.rea.engine\n\n"
                "/** Runs of code points as `start-end:value` (hex): Grapheme_Cluster_Break classes and\n"
                " *  Indic_Conjunct_Break values, numbered as in Windows/engine/src/GraphemeTables.h. */\n"
                "internal object GraphemeTables {\n"
                f"    /** {', '.join(f'{i} {c}' for i, c in enumerate(CLASSES))}. */\n"
                f"    const val BREAKS =\n{kt(breaks)}\n\n"
                f"    /** {', '.join(f'{i} {c}' for i, c in enumerate(INCB))}. */\n"
                f"    const val INDIC_CONJUNCT_BREAKS =\n{kt(incb)}\n}}\n")
    print(f"Unicode {v}: {len(breaks)} break ranges, {len(incb)} InCB ranges")


if __name__ == "__main__":
    main(sys.argv[1])
